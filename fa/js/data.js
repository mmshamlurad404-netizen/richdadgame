const BOARD_POS = (function () {
  const pos = [];
  for (let c = 0; c < 9; c++) pos.push({ r: 0, c });
  for (let r = 1; r < 9; r++) pos.push({ r, c: 8 });
  for (let c = 7; c >= 0; c--) pos.push({ r: 8, c });
  for (let r = 7; r >= 1; r--) pos.push({ r, c: 0 });
  return pos;
})();

